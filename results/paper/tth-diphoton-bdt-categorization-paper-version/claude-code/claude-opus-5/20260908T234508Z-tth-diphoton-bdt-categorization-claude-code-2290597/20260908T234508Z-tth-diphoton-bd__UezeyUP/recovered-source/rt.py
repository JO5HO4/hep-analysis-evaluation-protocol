import ROOT, numpy as np, math
ROOT.gROOT.SetBatch(True)
ROOT.RooMsgService.instance().setGlobalKillBelow(ROOT.RooFit.ERROR)
m=ROOT.RooRealVar("m_yy","m",105,160,"GeV"); m.setBins(55)
m.setRange("FULL",105,160); m.setRange("SBLO",105,120); m.setRange("SBHI",130,160)
print("A: TH1->RooDataHist")
th1=ROOT.TH1D("h","h",55,105,160)
rng=np.random.default_rng(1)
for i in range(55): th1.SetBinContent(i+1, float(abs(rng.normal(5,1))))
dh=ROOT.RooDataHist("dh","dh",ROOT.RooArgList(m),th1)
print(" ok", dh.numEntries())
print("B: gauss fit")
mean=ROOT.RooRealVar("mean","",125,118,132); sig=ROOT.RooRealVar("sig","",2,0.5,8)
g=ROOT.RooGaussian("g","",m,mean,sig)
r=g.fitTo(dh,ROOT.RooFit.Save(True),ROOT.RooFit.PrintLevel(-1),ROOT.RooFit.SumW2Error(True),ROOT.RooFit.Minimizer("Minuit2","migrad"))
print(" ok",r.status(),mean.getVal())
print("C: RooDataSet unbinned")
ds=ROOT.RooDataSet("ds","ds",ROOT.RooArgSet(m))
for v in rng.uniform(105,160,300):
    m.setVal(float(v)); ds.add(ROOT.RooArgSet(m))
print(" ok", ds.numEntries())
print("D: expo fit ranged")
a0=ROOT.RooRealVar("a0","",-0.02,-0.5,0.2)
e=ROOT.RooExponential("e","",m,a0)
r=e.fitTo(ds,ROOT.RooFit.Save(True),ROOT.RooFit.PrintLevel(-1),ROOT.RooFit.Range("SBLO,SBHI"),ROOT.RooFit.Minimizer("Minuit2","migrad"))
print(" ok", r.status(), r.minNll())
print("E: integral")
ns=ROOT.RooArgSet(m)
i1=e.createIntegral(ns, ROOT.RooFit.NormSet(ns), ROOT.RooFit.Range("SBLO")).getVal()
print(" ok", i1)
print("F: getVal with persistent normset")
m.setVal(120.0); print(" ", e.getVal(ns))
print("G: RooProduct / RooAddPdf / generateBinned")
mu=ROOT.RooRealVar("mu","",1,-5,20)
nsig=ROOT.RooRealVar("nsig","",5.0); nsig.setConstant(True)
nres=ROOT.RooRealVar("nres","",3.0); nres.setConstant(True)
nbkg=ROOT.RooRealVar("nbkg","",300.,0,5000)
prod=ROOT.RooProduct("mun","",ROOT.RooArgList(mu,nsig))
model=ROOT.RooAddPdf("model","",ROOT.RooArgList(g,g,e),ROOT.RooArgList(prod,nres,nbkg))
asi=model.generateBinned(ROOT.RooArgSet(m), ROOT.RooFit.ExpectedData(True))
print(" ok", asi.numEntries(), asi.sumEntries())
print("H: createNLL + RooAddition + RooMinimizer")
nll=model.createNLL(asi, ROOT.RooFit.Extended(True))
lst=ROOT.RooArgList(); lst.add(nll)
tot=ROOT.RooAddition("tot","",lst)
mini=ROOT.RooMinimizer(tot); mini.setPrintLevel(-1); mini.setStrategy(1)
st=mini.minimize("Minuit2","migrad"); hs=mini.hesse(); res=mini.save("f","f")
print(" ok",st,hs,res.status(),res.covQual(),res.minNll(),mu.getVal(),mu.getError())
print("I: cat + simultaneous + map datahist")
cat=ROOT.RooCategory("cat","cat"); cat.defineType("c1")
sim=ROOT.RooSimultaneous("sim","",cat); sim.addPdf(model,"c1")
try:
    hm=ROOT.std.map("string, RooDataHist*")()
    hm["c1"]=asi
    comb=ROOT.RooDataHist("comb","comb",ROOT.RooArgList(m),cat,hm)
    print(" ok comb", comb.numEntries())
except Exception as ex:
    print(" FAIL", ex)
print("J: workspace")
w=ROOT.RooWorkspace("w","w")
getattr(w,"import")(sim, ROOT.RooFit.RecycleConflictNodes())
w.writeToFile("/tmp/w.root")
print(" ok")
print("K: HS3")
try:
    t=ROOT.RooJSONFactoryWSTool(w); t.exportJSON("/tmp/w.json"); print(" ok")
except Exception as ex: print(" FAIL", type(ex).__name__, ex)
